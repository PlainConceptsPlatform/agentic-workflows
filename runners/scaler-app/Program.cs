// ---- workflow leases (affinity) ----
// One workflow run (repository_id + run_id + run_attempt) is served by one VM. The affinity
// label is minted onto the runner, so GitHub cannot hand that run's jobs to any other VM.
// The mutex is a real mutex only because the scaler runs a single instance (verified: B1
// App Service plan, maxElasticWorkerCount=1). Leases are persisted so a restart re-reads them.
var leasesByVm  = new ConcurrentDictionary<string, WorkflowLease>();
var leasesByKey = new ConcurrentDictionary<WorkflowKey, WorkflowLease>();
var leaseLock   = new object();
var leasesPath  = Path.Combine(dataDir, "leases.json");
// Per-VM liveness from /vm/heartbeat, sent by an independent process so a hung
// reset_state cannot silence it. Not persisted: a restart just re-learns it.
var vmHeartbeat = new ConcurrentDictionary<string, VmHeartbeat>();
long leaseGenCounter = 0;   // monotonic fencing token, bumped on every lease acquisition
try
{
    if (File.Exists(leasesPath))
        foreach (var l in JsonSerializer.Deserialize<List<WorkflowLease>>(File.ReadAllText(leasesPath)) ?? [])
            if (l is not null) { leasesByVm[l.VmInstanceId] = l; leasesByKey[l.Key] = l; }
}
catch (Exception e) { log.LogWarning("leases load failed: {m}", e.Message); }

void SaveLeases()
{
    lock (leaseLock)
        File.WriteAllText(leasesPath, JsonSerializer.Serialize(leasesByKey.Values.ToList()));
}
void ReleaseLocked(WorkflowLease l)
{
    leasesByVm.TryRemove(l.VmInstanceId, out _);
    leasesByKey.TryRemove(l.Key, out _);
    SaveLeases();
}
// Record a liveness signal in vmHeartbeat only. It deliberately does NOT touch the lease's
// LastActivity: that field means "last job served" and drives the idle grace, so updating
// it on every poll/heartbeat would keep a finished run's lease alive forever.
void TouchVm(string instanceId, string state, long? gen)
{
    lock (leaseLock)
    {
        var since = vmHeartbeat.TryGetValue(instanceId, out var prev) && prev.State == state
            ? prev.StateSince : DateTimeOffset.UtcNow;
        vmHeartbeat[instanceId] = new VmHeartbeat(DateTimeOffset.UtcNow, state, since, gen ?? 0);
    }
}

// ---- Azure (managed identity, no SDK) ----
string? armToken = null;
DateTimeOffset armTokenExpiry = DateTimeOffset.MinValue;
var tokenLock = new SemaphoreSlim(1, 1);
async Task<string> ArmToken()
{
    if (armToken is not null && DateTimeOffset.UtcNow < armTokenExpiry) return armToken;
    await tokenLock.WaitAsync();
    try
    {
        if (armToken is not null && DateTimeOffset.UtcNow < armTokenExpiry) return armToken;
        var ep = Req("IDENTITY_ENDPOINT");
        var hdr = Req("IDENTITY_HEADER");
        using var req = new HttpRequestMessage(HttpMethod.Get,
            $"{ep}?resource=https://management.azure.com/&api-version=2019-08-01");
        req.Headers.Add("X-IDENTITY-HEADER", hdr);
        var resp = await http.SendAsync(req);
        resp.EnsureSuccessStatusCode();
        var node = JsonNode.Parse(await resp.Content.ReadAsStringAsync())!;
        armToken = node["access_token"]!.GetValue<string>();
        var expiresOn = node["expires_on"]!.GetValue<string>();
        armTokenExpiry = DateTimeOffset.FromUnixTimeSeconds(long.Parse(expiresOn)).AddMinutes(-5);
        return armToken;
    }
    finally { tokenLock.Release(); }
}

async Task<HttpResponseMessage> Arm(HttpMethod method, string url, object? body = null)
{
    using var req = new HttpRequestMessage(method, url);
    req.Headers.Authorization = new("Bearer", await ArmToken());
    if (body is not null)
        req.Content = new StringContent(JsonSerializer.Serialize(body), Encoding.UTF8, "application/json");
    return await http.SendAsync(req);
}

// GET a GitHub API URL with the org PAT; null on any non-success so callers treat null as
// "unknown" and keep their current state rather than acting on a bad read.
async Task<JsonNode?> GetJson(string url)
{
    try
    {
        using var req = new HttpRequestMessage(HttpMethod.Get, url);
        req.Headers.Authorization = new("Bearer", ghPat);
        req.Headers.Accept.ParseAdd("application/vnd.github+json");
        req.Headers.Add("X-GitHub-Api-Version", "2022-11-28");
        var resp = await http.SendAsync(req);
        return resp.IsSuccessStatusCode ? JsonNode.Parse(await resp.Content.ReadAsStringAsync()) : null;
    }
    catch (Exception e) { log.LogWarning("github get failed: {m}", e.Message); return null; }
}

// The repos to poll for a queued job the webhook missed. A configured list wins; otherwise
// every private repo of the org that has had a push in the last two weeks, newest first, so
// a renamed or added repo needs no configuration and a large org still bounds the polls.
async Task<IReadOnlyList<string>> WatchedReposAsync()
{
    if (watchRepos.Length > 0) return watchRepos;

    lock (watchedLock)
        if (DateTimeOffset.UtcNow - watchedAt < TimeSpan.FromMinutes(30)) return watchedCache;

    var discovered = new List<string>();
    var since = DateTimeOffset.UtcNow.AddDays(-14).ToString("O");
    for (var page = 1; page <= 5; page++)
    {
        var repos = await GetJson(
            $"https://api.github.com/orgs/{ghOrg}/repos?type=private&sort=updated&per_page=100&page={page}");
        var batch = repos as JsonArray ?? [];
        foreach (var repo in batch)
        {
            if (repo?["archived"]?.GetValue<bool>() == true) continue;
            if (repo?["has_actions"]?.GetValue<bool>() == false) continue;
            if (repo?["pushed_at"]?.GetValue<string>() is { Length: > 0 } pushed
                && string.CompareOrdinal(pushed, since) < 0) continue;
            if (repo?["name"]?.GetValue<string>() is { Length: > 0 } name) discovered.Add(name);
        }
        if (batch.Count < 100) break;
    }

    if (discovered.Count == 0) return watchedCache;

    lock (watchedLock)
    {
        watchedCache = discovered;
        watchedAt = DateTimeOffset.UtcNow;
    }
    return discovered;
}

async Task<int> Capacity()
{
    var resp = await Arm(HttpMethod.Get, $"{vmssUrl}?api-version={ArmApi}");
    resp.EnsureSuccessStatusCode();
    return JsonNode.Parse(await resp.Content.ReadAsStringAsync())!["sku"]!["capacity"]!.GetValue<int>();
}

async Task<List<(string Id, string State)>> Instances()
{
    var resp = await Arm(HttpMethod.Get, $"{vmssUrl}/virtualMachines?api-version={ArmApi}");
    resp.EnsureSuccessStatusCode();
    var node = JsonNode.Parse(await resp.Content.ReadAsStringAsync())!;
    return (node["value"] as JsonArray ?? [])
        .Select(v => (v!["instanceId"]!.GetValue<string>(),
                      v["properties"]?["provisioningState"]?.GetValue<string>() ?? "Unknown"))
        .ToList();
}

async Task SetCapacity(int target)
{
    target = Math.Min(target, MaxVms);
    var resp = await Arm(HttpMethod.Patch, $"{vmssUrl}?api-version={ArmApi}",
        new { sku = new { capacity = target } });
    if (!resp.IsSuccessStatusCode)
        log.LogError("capacity patch to {t} failed: {s} {b}", target, resp.StatusCode, await resp.Content.ReadAsStringAsync());
    else
        log.LogInformation("capacity patch -> {t}", target);
}

async Task DeleteInstance(string id)
{
    var resp = await Arm(HttpMethod.Post, $"{vmssUrl}/delete?forceDeletion=true&api-version={ArmApi}",
        new { instanceIds = new[] { id } });
    if (!resp.IsSuccessStatusCode)
        log.LogError("delete instance {id} failed: {s} {b}", id, resp.StatusCode, await resp.Content.ReadAsStringAsync());
}

