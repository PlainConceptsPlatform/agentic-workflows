app.MapPost("/api/cancel/{id}", async (HttpContext ctx, long id) =>
{
    if (!IsAuthenticated(ctx)) return Results.Unauthorized();
    var user = ctx.Request.Headers["X-MS-CLIENT-PRINCIPAL-NAME"].ToString();
    user = string.IsNullOrEmpty(user) ? "panel" : user;

    // Find the job in the ledger to get repo + runId for cancellation.
    if (!ledger.TryGetValue(id, out var entry))
        return Results.Json(new { error = $"job {id} not found in ledger" }, statusCode: 404);

    if (entry.Status != "queued" && entry.Status != "in_progress")
        return Results.Json(new { error = $"job {id} is {entry.Status}, cannot cancel" }, statusCode: 409);

    // Cancel via GitHub API: POST /repos/{owner}/{repo}/actions/jobs/{job_id}/cancel
    var repo = entry.Repo ?? $"{ghOrg}/unknown";
    using var req = new HttpRequestMessage(HttpMethod.Post,
        $"https://api.github.com/repos/{repo}/actions/jobs/{id}/cancel");
    req.Headers.Authorization = new("Bearer", ghPat);
    req.Headers.Accept.ParseAdd("application/vnd.github+json");
    req.Headers.Add("X-GitHub-Api-Version", "2022-11-28");
    var resp = await http.SendAsync(req);
    if (!resp.IsSuccessStatusCode)
    {
        var body = await resp.Content.ReadAsStringAsync();
        log.LogWarning("cancel job {id} by {u} failed: {s} {b}", id, user, resp.StatusCode, body);
        return Results.Json(new { error = $"GitHub returned {resp.StatusCode}", detail = body }, statusCode: 502);
    }

    log.LogInformation("job {id} cancelled by {u} (repo={repo})", id, user, repo);
    // Remove from ledger optimistically; GitHub will send a completed webhook too.
    ledger.TryRemove(id, out _);
    SaveLedger();
    _ = Task.Run(() => Evaluate($"cancel:{id}"));
    return Results.Json(new { ok = true, id, cancelledBy = user });
});

// Fetch a workflow run's display title (the commit message shown on GitHub's Actions UI)
// and merge it into every job in the ledger that shares that run_id. Cached per run_id so
// we never hit the API more than once per run, even if the webhook fires for several jobs.
var runTitleCache = new ConcurrentDictionary<long, string>();
async Task TryEnrichRunTitle(long jobId, string? repo, long? runId)
{
    if (runId is not long rid || string.IsNullOrEmpty(repo)) return;
    // Already have a title for this run? Just stamp it onto this job and bail.
    if (runTitleCache.TryGetValue(rid, out var cached))
    {
        if (ledger.TryGetValue(jobId, out var j) && j.RunTitle != cached)
        {
            ledger[jobId] = j with { RunTitle = cached };
            SaveLedger();
        }
        return;
    }
    try
    {
        // run_id's are global across the org, so /repos/{repo}/actions/runs/{run_id} works
        // even if repo here is the webhook's repo (which it is). Use the full_name.
        using var req = new HttpRequestMessage(HttpMethod.Get,
            $"https://api.github.com/repos/{repo}/actions/runs/{rid}");
        req.Headers.Authorization = new("Bearer", ghPat);
        req.Headers.Accept.ParseAdd("application/vnd.github+json");
        req.Headers.Add("X-GitHub-Api-Version", "2022-11-28");
        var resp = await http.SendAsync(req);
        if (!resp.IsSuccessStatusCode) { return; }
        var node = JsonNode.Parse(await resp.Content.ReadAsStringAsync())!;
        var title = node["display_title"]?.GetValue<string>();
        if (string.IsNullOrEmpty(title)) return;
        runTitleCache[rid] = title;
        // Stamp onto every ledger entry that shares this run (queued + in_progress).
        var changed = false;
        foreach (var kv in ledger)
        {
            if (kv.Value.RunId == rid && kv.Value.RunTitle != title)
            {
                ledger[kv.Key] = kv.Value with { RunTitle = title };
                changed = true;
            }
        }
        if (changed) SaveLedger();
    }
    catch (Exception e) { log.LogWarning("enrich run title for job {id} run {rid} failed: {m}", jobId, rid, e.Message); }
}

app.MapPost("/github", async (HttpRequest r) =>
{
    string body;
    using (var sr = new StreamReader(r.Body)) body = await sr.ReadToEndAsync();
    if (!SignatureValid(body, r.Headers["X-Hub-Signature-256"]))
        return Results.Unauthorized();
    var node = JsonNode.Parse(body)!;
    var evt = r.Headers["X-GitHub-Event"].ToString();

    // workflow_run's "completed" is the only clean signal that a run is over: a
    // workflow_job "completed" never tells us whether it was the last job of the run.
    // Releasing here lets the next run claim the VM without waiting out the lease TTL.
    if (evt == "workflow_run")
    {
        if (node["action"]?.GetValue<string>() == "completed"
            && node["repository"]?["id"]?.GetValue<long>() is long rrid
            && node["workflow_run"]?["id"]?.GetValue<long>() is long wrid)
        {
            var key = new WorkflowKey(rrid, wrid, node["workflow_run"]?["run_attempt"]?.GetValue<int>() ?? 1);
            lock (leaseLock)
                if (leasesByKey.TryGetValue(key, out var done)) ReleaseLocked(done);
            _ = Task.Run(() => Evaluate("workflow_run:completed"));
        }
        return Results.Ok("ok");
    }
    if (evt != "workflow_job") return Results.Ok("ignored event");

    var job = node["workflow_job"]!;
    var labels = (job["labels"] as JsonArray ?? []).Select(l => l!.GetValue<string>()).ToList();
    var isPrivate = node["repository"]?["private"]?.GetValue<bool>() ?? false;
    if (!labels.Any(IsOurs) || !isPrivate) return Results.Ok("not ours");
    // The affinity label (when the run carries one) names the workflow run's dedicated VM.
    var affinity = labels.FirstOrDefault(l => l.StartsWith("affinity-", StringComparison.Ordinal));

    var id = job["id"]!.GetValue<long>();
    var action = node["action"]!.GetValue<string>();
    var repo = node["repository"]?["full_name"]?.GetValue<string>();
    var jobName = job["name"]?.GetValue<string>();
    var branch = job["head_branch"]?.GetValue<string>();
    var htmlUrl = job["html_url"]?.GetValue<string>();
    var runId = job["run_id"]?.GetValue<long>();
    var workflowName = job["workflow_name"]?.GetValue<string>();
    var repoId = node["repository"]?["id"]?.GetValue<long>();
    var runAttempt = job["run_attempt"]?.GetValue<int>();
    switch (action)
    {
        case "queued":
            ledger[id] = new("queued", DateTimeOffset.UtcNow, repo, jobName, branch, htmlUrl, runId, workflowName,
                RepositoryId: repoId, RunAttempt: runAttempt, AffinityLabel: affinity);
            _ = TryEnrichRunTitle(id, repo, runId);
            break;
        case "in_progress":
            // Preserve the metadata from the queued webhook in case the in_progress event
            // arrives without it (GitHub sometimes omits fields on later actions).
            var prev = ledger.TryGetValue(id, out var existing) ? existing : null;
            ledger[id] = new("in_progress", DateTimeOffset.UtcNow,
                repo ?? prev?.Repo, jobName ?? prev?.JobName,
                branch ?? prev?.Branch, htmlUrl ?? prev?.HtmlUrl, runId ?? prev?.RunId,
                workflowName ?? prev?.WorkflowName, prev?.RunTitle,
                repoId ?? prev?.RepositoryId, runAttempt ?? prev?.RunAttempt, affinity ?? prev?.AffinityLabel);
            fruitlessCycles = 0;
            lastJobActivity = DateTimeOffset.UtcNow;
            // Backfill the title if the queued step didn't manage to yet.
            if (string.IsNullOrEmpty(ledger[id].RunTitle))
                _ = TryEnrichRunTitle(id, repo ?? prev?.Repo, runId ?? prev?.RunId);
            break;
        case "completed":
            ledger.TryRemove(id, out _);
            lastJobActivity = DateTimeOffset.UtcNow;
            break;
    }
    SaveLedger();
    log.LogInformation("webhook: job {id} {a}; demand now {d}", id, action, Demand());
    _ = Task.Run(() => Evaluate($"webhook:{action}"));
    return Results.Ok("ok");
});

app.MapPost("/vm/jit", async (HttpRequest r) =>
{
    if (!VmAuthorized(r)) return Results.Unauthorized();
    var node = JsonNode.Parse(await new StreamReader(r.Body).ReadToEndAsync())!;
    var instanceId = node["instanceId"]!.GetValue<string>();
    var known = (await Instances()).Any(i => i.Id == instanceId);
    if (!known) { log.LogWarning("jit request from unknown instance {id}", instanceId); return Results.Unauthorized(); }

    // A VM asks for work. Under the lease lock we decide: serve this VM's own run (or hold
    // for it), claim an unowned run, or serve an unlabelled CI job. Return codes drive
    // job.sh: 200 = JIT follows, 202 = hold (lease active, nothing queued yet, do NOT
    // retire), 204 = nothing to do (job.sh applies FIRST_WAIT/IDLE_LIMIT).
    WorkflowLease? lease = null;
    var serveCi = false;
    lock (leaseLock)
    {
        if (leasesByVm.TryGetValue(instanceId, out var held))
        {
            if (ledger.Any(kv => kv.Value.Status == "queued" && kv.Value.AffinityLabel == held.AffinityLabel))
            {
                lease = held with { LastActivity = DateTimeOffset.UtcNow, JobsCompleted = held.JobsCompleted + 1 };
                leasesByVm[instanceId] = lease;
                leasesByKey[held.Key] = lease;
                SaveLeases();
            }
            else if (ledger.Any(kv => kv.Value.Status == "in_progress" && kv.Value.AffinityLabel == held.AffinityLabel)
                     || DateTimeOffset.UtcNow - held.LastActivity < LeaseGrace)
            {
                leasesByVm[instanceId] = held with { LastActivity = DateTimeOffset.UtcNow };
                SaveLeases();
                log.LogInformation("instance {id} holds lease {l}; nothing queued yet, holding", instanceId, held.AffinityLabel);
                return Results.StatusCode(202);
            }
            else
            {
                log.LogInformation("instance {id} releasing finished lease {l}", instanceId, held.AffinityLabel);
                ReleaseLocked(held);
            }
        }

        if (lease is null && !serveCi)
        {
            var claim = ledger
                .Where(kv => kv.Value.Status == "queued" && kv.Value.AffinityLabel is not null
                             && kv.Value.RepositoryId is not null && kv.Value.RunAttempt is not null)
                .GroupBy(kv => new WorkflowKey(kv.Value.RepositoryId!.Value, kv.Value.RunId!.Value, kv.Value.RunAttempt!.Value))
                .FirstOrDefault(g => !leasesByKey.ContainsKey(g.Key));
            if (claim is not null)
            {
                var lbl = claim.First().Value.AffinityLabel!;
                lease = new WorkflowLease(claim.Key, lbl, instanceId, "Active", DateTimeOffset.UtcNow, 1);
                leasesByKey[lease.Key] = lease;
                leasesByVm[instanceId] = lease;
                SaveLeases();
                log.LogInformation("instance {id} claimed lease {l}", instanceId, lbl);
            }
            else if (ledger.Any(kv => kv.Value.Status == "queued" && kv.Value.AffinityLabel is null))
            {
                serveCi = true;
            }
        }
    }

    if (lease is null && !serveCi)
    {
        log.LogInformation("instance {id} asked for work; none queued and no unlabelled job waiting", instanceId);
        return Results.NoContent();
    }

    var jitLabels = lease is null ? new[] { ciLabel } : new[] { agentLabel, lease.AffinityLabel };
    var jit = await MintJit($"i{instanceId}-{DateTimeOffset.UtcNow.ToUnixTimeSeconds()}", jitLabels);
    if (jit is null) return Results.StatusCode(502);
    log.LogInformation("jit issued to instance {id} (labels={l})", instanceId, string.Join(",", jitLabels));
    return Results.Text(jit);
});

app.MapPost("/vm/done", async (HttpRequest r) =>
{
    if (!VmAuthorized(r)) return Results.Unauthorized();
    var node = JsonNode.Parse(await new StreamReader(r.Body).ReadToEndAsync())!;
    var instanceId = node["instanceId"]!.GetValue<string>();
    // A retiring VM gives up whatever run it held, so a fresh VM can claim it immediately.
    lock (leaseLock)
        if (leasesByVm.TryGetValue(instanceId, out var retiring)) ReleaseLocked(retiring);
    var gotJob = node["ranJob"]?.GetValue<bool>() ?? false;
    // jobsRun is how we measure reuse: 1 means the VM paid a full boot for a single job,
    // which is the waste the reuse loop exists to remove.
    var jobsRun = node["jobsRun"]?.GetValue<int>() ?? (gotJob ? 1 : 0);
    totalVmsRetired++;
    totalJobsServed += jobsRun;
    log.LogInformation(
        "instance {id} done: jobsRun={n} (lifetime avg {avg:F1} jobs/VM over {vms} VMs); deleting",
        instanceId, jobsRun, totalVmsRetired == 0 ? 0 : (double)totalJobsServed / totalVmsRetired, totalVmsRetired);
    if (!gotJob)
    {
        fruitlessCycles++;
        if (fruitlessCycles >= 3 && DateTimeOffset.UtcNow - lastJobActivity > TimeSpan.FromMinutes(30))
        {
            log.LogWarning("{n} fruitless VM cycles with no job activity; clearing stale queued ledger", fruitlessCycles);
            foreach (var kv in ledger.Where(kv => kv.Value.Status == "queued").ToList())
                ledger.TryRemove(kv.Key, out _);
            SaveLedger();
            fruitlessCycles = 0;
        }
    }
    await DeleteInstance(instanceId);
    _ = Task.Run(() => DeleteGhostRunner(instanceId));  // fire-and-forget: Azure delete already in flight
    _ = Task.Run(async () => { await Task.Delay(TimeSpan.FromSeconds(30)); await Evaluate("vm-done"); });
    return Results.Ok("bye");
});

// reconcile sweep: prune forgotten ledger entries, clean failed instances, kill zombie VMs,
// and re-evaluate. A zombie is a VM that is "Succeeded" in Azure but has no runner registered
// on GitHub job.sh crashed or the runner process died, and /vm/done was never called, so the
// scaler counts it as active capacity while nothing can serve jobs.
var lastZombieCheck = DateTimeOffset.UtcNow;
_ = Task.Run(async () =>
{
    while (true)
    {
        try
        {
            await Task.Delay(TimeSpan.FromMinutes(5));
            var changed = false;
            foreach (var kv in ledger.ToList())
            {
                var age = DateTimeOffset.UtcNow - kv.Value.UpdatedUtc;
                var stale = kv.Value.Status == "in_progress" ? age > TimeSpan.FromHours(8)
                                                             : age > TimeSpan.FromHours(24);
                if (stale) { ledger.TryRemove(kv.Key, out _); changed = true; log.LogWarning("pruned stale job {id}", kv.Key); }
            }
            if (changed) SaveLedger();

            // Leases whose VM is gone (deleted out from under us) or that have gone silent
            // for hours must be released, or the run can never be re-claimed by a fresh VM.
            try
            {
                var alive = (await Instances()).Select(i => i.Id).ToHashSet();
                foreach (var (vm, lease) in leasesByVm.ToList())
                    if (!alive.Contains(vm) || DateTimeOffset.UtcNow - lease.LastActivity > TimeSpan.FromHours(2))
                    {
                        log.LogWarning("releasing orphan lease {l} from {vm} (alive={a})", lease.AffinityLabel, vm, alive.Contains(vm));
                        lock (leaseLock) ReleaseLocked(lease);
                    }
            }
            catch (Exception e) { log.LogWarning("lease orphan sweep failed: {m}", e.Message); }

            // Title backfill: jobs that entered the ledger before the webhook enrich was
            // available (or that missed their webhook) never got a run display_title. Re-try
            // those here so the panel fills in on the next sweep instead of waiting forever.
            // Serialized with a small gap and capped per sweep to keep API calls gentle.
            var pending = 0;
            foreach (var kv in ledger)
            {
                if (string.IsNullOrEmpty(kv.Value.RunTitle) && kv.Value.RunId is long rid2
                    && !string.IsNullOrEmpty(kv.Value.Repo) && pending < 4)
                {
                    pending++;
                    _ = TryEnrichRunTitle(kv.Key, kv.Value.Repo, rid2);
                    await Task.Delay(TimeSpan.FromSeconds(1));
                }
            }

            // Zombie detection: if we have active VMs but no runner is registered on GitHub,
            // those VMs are dead. Delete them so the evaluate pass can boot fresh ones.
            // Check at most every 10 minutes to avoid burning API quota on every sweep.
            if (DateTimeOffset.UtcNow - lastZombieCheck > TimeSpan.FromMinutes(10))
            {
                lastZombieCheck = DateTimeOffset.UtcNow;
                var instances = await Instances();
                var active = instances.Where(i => i.State is not "Deleting" and not "Failed").ToList();
                if (active.Count > 0)
                {
                    var ghRunners = await GitHubRunnerCount();
                    if (ghRunners == 0)
                    {
                        // Guard: when VMs are legitimately between jobs (JIT is single-use —
                        // run.sh exits after each job, and the runner record is "offline"
                        // until job.sh mints the next JIT), we briefly have 0 online runners
                        // with active VMs. That is normal, not zombies. Only nuke after a
                        // sustained silence: no job activity for 5 minutes.
                        var sinceActivity = DateTimeOffset.UtcNow - lastJobActivity;
                        if (sinceActivity < TimeSpan.FromMinutes(5))
                        {
                            log.LogInformation("zombie detection: {n} VM(s) but 0 online runners; {s:F0}s since last job activity < 5min grace, skipping nuke",
                                active.Count, sinceActivity.TotalSeconds);
                        }
                        else
                        {
                            log.LogWarning("zombie detection: {n} active VM(s) but 0 runners on GitHub for {s:F0}s; deleting all instances",
                                active.Count, sinceActivity.TotalSeconds);
                            foreach (var inst in active)
                                await DeleteInstance(inst.Id);
                            fruitlessCycles = 0;
                            // Do NOT clear the queued ledger. Those entries came from real
                            // GitHub webhooks for jobs that are genuinely waiting. Deleting
                            // them here makes the scaler forget demand that still exists on
                            // GitHub, so the queued jobs sit unassigned until the next webhook.
                            // GitHub re-issues webhooks and a fresh VM will pick them up.
                        }
                    }
                    else
                    {
                        // Dead VMs may also show as "Succeeded" for days; check each instance's
                        // registration individually against GitHub's runner list.
                        var runnerNames = new HashSet<string>();
                        try
                        {
                            var url = $"https://api.github.com/orgs/{ghOrg}/actions/runners?per_page=100";
                            while (url is not null)
                            {
                                using var req = new HttpRequestMessage(HttpMethod.Get, url);
                                req.Headers.Authorization = new("Bearer", ghPat);
                                req.Headers.Accept.ParseAdd("application/vnd.github+json");
                                req.Headers.Add("X-GitHub-Api-Version", "2022-11-28");
                                var resp = await http.SendAsync(req);
                                resp.EnsureSuccessStatusCode();
                                var node = JsonNode.Parse(await resp.Content.ReadAsStringAsync())!;
                                var count = (node["runners"] as JsonArray ?? []).Count;
                                foreach (var r in node["runners"] as JsonArray ?? [])
                                    if (r?["name"]?.GetValue<string>() is string n)
                                        runnerNames.Add(n);
                                // Same Link-header fix as GitHubRunnerCount: avoid throwing
                                // on the common single-page case.
                                IEnumerable<string>? linkHeaders = null;
                                resp.Headers.TryGetValues("Link", out linkHeaders);
                                var link = linkHeaders?.FirstOrDefault() ?? "";
                                var match = System.Text.RegularExpressions.Regex.Match(link, "<([^>]+)>; rel=\"next\"");
                                url = match.Success ? match.Groups[1].Value : null;
                            }
                        }
                        catch (Exception e) { log.LogWarning("runner name list error: {m}", e.Message); }

                        foreach (var inst in active)
                        {
                            // Runner names are "i{instanceId}-{timestamp}". Match by prefix.
                            var registered = runnerNames.Any(n => n.StartsWith($"i{inst.Id}-"));
                            if (!registered)
                            {
                                // Give freshly-booted VMs time to register before declaring them zombies.
                                // A VM that was just created by Evaluate() needs ~60s to boot + register.
                                log.LogInformation("instance {id} not yet registered on GitHub", inst.Id);
                            }
                        }
                    }
                }
            }

            await Evaluate("timer");
        }
        catch (Exception e) { log.LogError("reconcile loop: {m}", e.Message); }
    }
});

app.Run();

record JobEntry(string Status, DateTimeOffset UpdatedUtc, string? Repo = null, string? JobName = null, string? Branch = null, string? HtmlUrl = null, long? RunId = null, string? WorkflowName = null, string? RunTitle = null,
    long? RepositoryId = null, int? RunAttempt = null, string? AffinityLabel = null);

// Workflow-run identity for the affinity lease. run_attempt is part of the key so a rerun
// (same run_id, new attempt) gets its own lease and its own VM instead of colliding.
record WorkflowKey(long RepositoryId, long RunId, int RunAttempt);
record WorkflowLease(WorkflowKey Key, string AffinityLabel, string VmInstanceId,
                     string Status, DateTimeOffset LastActivity, int JobsCompleted);
